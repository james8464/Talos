def records(app, path):
    if app == "Contacts":
        try:
            addresses = mac_context.read(path, """SELECT a.Z_PK,a.ZLABEL,a.ZSTREET,
                a.ZCITY,a.ZSTATE,a.ZZIPCODE,a.ZCOUNTRYNAME,r.ZFIRSTNAME,r.ZLASTNAME
                FROM ZABCDPOSTALADDRESS a JOIN ZABCDRECORD r ON r.Z_PK=a.ZOWNER""")
        except sqlite3.Error:
            addresses = []
        for key, label, street, city, region, postal, country, first, last in addresses:
            name = " ".join(filter(None, (first, last)))
            yield f"address-{key}", " · ".join(filter(None, (
                name, "postal address", label, street, city, region, postal, country,
            )))
        for key, name, org, nickname, phones, emails in mac_context.contact_rows(path, -1):
            yield str(key), " · ".join(filter(None, (name, org, nickname, phones, emails)))
        try:
            family = mac_context.read(path, """SELECT n.Z_PK,n.ZLABEL,n.ZNAME FROM ZABCDRELATEDNAME n
                JOIN ZABCDRECORD r ON r.Z_PK=n.ZOWNER WHERE r.ZCONTAINERWHERECONTACTISME IS NOT NULL
                AND n.ZNAME IS NOT NULL""")
        except sqlite3.Error:
            family = []
        for key, label, name in family:
            role = re.sub(r"[^\w -]", "", label or "").strip("_")
            yield f"family-{key}", f"My family · {role} · {name}"
        return
    for key, peer, outgoing, stamp, body in mac_context.app_rows(app, path, limit=-1, text_limit=None):
        direction = "sent" if outgoing == 1 else "received" if outgoing == 0 else "mail"
        try:
            day = datetime.fromtimestamp(stamp, UTC).date().isoformat()
        except (TypeError, ValueError, OSError, OverflowError):
            day = ""
        yield str(key), " · ".join(filter(None, (day, peer, direction, body)))


def signature(path):
    parts = []
    for file in (path, Path(str(path) + "-wal")):
        try:
            info = file.stat()
            parts.append((info.st_ino, info.st_size, info.st_mtime_ns, info.st_ctime_ns))
        except FileNotFoundError:
            if file == path:
                raise
    return "v2:" + repr(parts)


def source_signature(app, path):
    revision = "contacts-addresses:" if app == "Contacts" else ""
    return revision + signature(path)


def publish_overview(state, relatives, counts):
    folder = state / "Talos Memory"
    folder.mkdir(mode=0o700, parents=True, exist_ok=True)
    path = folder / "Personal knowledge overview.md"
    lines = ["# Personal memory overview", "", "Generated by Talos from enabled local sources.", "",
             "## Indexed records", ""]
    lines.extend(f"- {app}: {n:,}" for app, n in sorted(counts.items()))
    sections = [("Family relationships from Contacts", sorted(relatives))]
    facts_db = state / "agent.sqlite3"
    if facts_db.is_file():
        with closing(sqlite3.connect(facts_db.resolve().as_uri() + "?mode=ro", uri=True)) as facts:
            if facts.execute("SELECT 1 FROM sqlite_master WHERE name='personal_facts'").fetchone():
                rows = facts.execute("SELECT subject,value FROM personal_facts WHERE session='text' ORDER BY subject")
                sections.append(("Facts saved in private messages", [f"{key}: {value}" for key, value in rows]))
    for title, values in sections:
        if values:
            lines.extend(["", "## " + title, ""])
            # Indented Markdown renders source text literally, including links and embeds.
            lines.extend("    " + " ".join(value.split()) for value in values)
    content = "\n".join(lines) + "\n"
    if path.exists() and path.read_text() == content:
        return
    with tempfile.NamedTemporaryFile(mode="w", dir=folder, delete=False) as tmp:
        tmp.write(content)
    Path(tmp.name).replace(path)


class SourceUnavailable(Exception):
    pass


def source_records(app, source):
    try:
        yield from records(app, source)
    except (OSError, sqlite3.Error) as error:
        raise SourceUnavailable from error


def refresh_source(db, app, source):
    src = str(source)
    before = source_signature(app, source)
    cached = db.execute("""SELECT i.signature,s.signature FROM indexed_sources i JOIN source_summary s
                          USING(source) WHERE i.source=?""", (src,)).fetchone()
    if cached == (before, before):
        try:
            mac_context.read(source, "SELECT count(*) FROM sqlite_master")
        except sqlite3.Error as error:
            raise SourceUnavailable from error
        return
    db.execute("DELETE FROM stage")
    db.executemany("INSERT OR REPLACE INTO stage VALUES(?,?)", source_records(app, source))
    after = source_signature(app, source)
    db.execute("DELETE FROM old")
    db.execute("INSERT INTO old SELECT record,rowid FROM personal WHERE source=?", (src,))
    db.execute("""DELETE FROM personal WHERE rowid IN (SELECT old.id FROM old
                  LEFT JOIN stage USING(record) WHERE stage.record IS NULL)""")
    db.execute("""UPDATE personal SET body=(SELECT body FROM stage WHERE record=personal.record)
                  WHERE rowid IN (SELECT old.id FROM old JOIN stage USING(record)
                  JOIN personal p ON p.rowid=old.id WHERE stage.body IS NOT p.body)""")
    db.execute("""INSERT INTO personal SELECT ?,?,stage.record,stage.body FROM stage LEFT JOIN old
                  USING(record) WHERE old.id IS NULL""", (app, src))
    stamp = after if before == after else ""
    count = db.execute("SELECT count(*) FROM stage").fetchone()[0]
    relatives = [r[0] for r in db.execute("SELECT body FROM stage WHERE record GLOB 'family-*'")] if app == "Contacts" else []
    db.execute("INSERT OR REPLACE INTO indexed_sources VALUES(?,?)", (src, stamp))
    db.execute("INSERT OR REPLACE INTO source_summary VALUES(?,?,?,?,?)",
               (src, app, stamp, count, json.dumps(relatives)))


def store_import_count(db, source, app, count):
    signature = memory_connections.CATALOG_SIGNATURE if app == "Projects" else ""
    db.execute("""INSERT INTO source_summary VALUES(?,?,?,?,'[]') ON CONFLICT(source)
                  DO UPDATE SET app=excluded.app,signature=excluded.signature,count=excluded.count,relatives='[]'
                  WHERE (app,signature,count,relatives) IS NOT (excluded.app,excluded.signature,excluded.count,'[]')""",
               (source, app, signature, count))


def refresh_import(db, app, source, records):
    """Reconcile one exported source while retaining FTS rowids used by evidence receipts."""
    db.execute("CREATE TEMP TABLE IF NOT EXISTS import_rows(record, body)")
    db.execute("""CREATE TEMP TABLE IF NOT EXISTS import_matches(
        record, ordinal INTEGER, old_id INTEGER, new_id INTEGER, PRIMARY KEY(record,ordinal))""")
    db.execute("DELETE FROM import_rows")
    db.execute("DELETE FROM import_matches")
    count = db.executemany("INSERT INTO import_rows VALUES(?,?)", records).rowcount
    if app == "Projects":
        memory_connections.update_project_catalog(db, source, db.execute("SELECT record FROM import_rows"))

    # Exports can repeat a key. Match each occurrence in input order, including on
    # migration from an older index. Staging in SQLite keeps large texts off the heap.
    db.execute("""INSERT INTO import_matches(record,ordinal,old_id)
                  SELECT record,row_number() OVER (PARTITION BY record ORDER BY rowid),rowid
                  FROM personal WHERE source=?""", (source,))
    db.execute("""INSERT INTO import_matches(record,ordinal,new_id)
                  SELECT record,row_number() OVER (PARTITION BY record ORDER BY rowid),rowid
                  FROM import_rows WHERE true
                  ON CONFLICT(record,ordinal) DO UPDATE SET new_id=excluded.new_id""")
    db.execute("""DELETE FROM personal WHERE rowid IN (
                  SELECT old_id FROM import_matches WHERE new_id IS NULL)""")
    db.execute("""UPDATE personal SET body=n.body
                  FROM import_matches m JOIN import_rows n ON n.rowid=m.new_id
                  WHERE personal.rowid=m.old_id AND personal.body IS NOT n.body""")
    db.execute("""INSERT INTO personal(app,source,record,body)
                  SELECT ?,?,n.record,n.body FROM import_matches m JOIN import_rows n ON n.rowid=m.new_id
                  WHERE m.old_id IS NULL ORDER BY n.rowid""", (app, source))
    return count


def search_terms(query):
    query = query.replace("“", '"').replace("”", '"')
    if query.count('"') % 2:
        raise ValueError("Close the quotation marks around the phrase.")
    terms = []
    for i, section in enumerate(query.split('"')):
        words = re.findall(r"[^\W_]+", section.casefold())
        if i % 2 and words:
            terms.append(" ".join(words))
        else:
            terms.extend(words)
    terms = list(dict.fromkeys(terms))
    if not 1 <= len(terms) <= 16:
        raise ValueError("Enter between one and sixteen search terms or quoted phrases.")
    return " AND ".join(f'"{term}"' for term in terms)


def search(state, library, query, app_filter=None):
    """Read the latest committed index without waiting on a source refresh."""
    try:
        match = search_terms(query)
    except ValueError as error:
        return {"private": True, "reply": str(error)}
    path = state / mac_context.INDEX_NAME
    if not path.exists():
        sync(state, library)
    enabled = mac_context.enabled(state)
    live_apps = enabled if app_filter is None else enabled & {app_filter}
    uri = path.resolve().as_uri() + "?mode=ro"
    with closing(sqlite3.connect(uri, uri=True, timeout=1)) as db:
        if live_apps and sources_changed(db, library, live_apps):
            try:
                sync(state, library, lock_timeout=0)
            except sqlite3.OperationalError as error:
                if (getattr(error, "sqlite_errorcode", 0) & 0xff) not in {
                    sqlite3.SQLITE_BUSY, sqlite3.SQLITE_LOCKED,
                }:
                    raise
        enabled.update(row[0] for row in db.execute(
            "SELECT app FROM source_summary WHERE source=? OR source GLOB ?",
            (personal_files.SOURCE, knowledge_sources.PREFIX + "*"),
        ))
        if app_filter and app_filter not in enabled:
            return {"private": True, "reply": f"{app_filter} is disabled in private sources."}
        apps = sorted({app_filter} if app_filter else enabled)
        placeholders = ",".join("?" for _ in apps)
        rows = db.execute(f"""SELECT app,record,snippet(personal,3,'','',' … ',24)
                              FROM personal WHERE personal MATCH ? AND app IN ({placeholders})
                              ORDER BY rank LIMIT 9""", (match, *apps)).fetchall() if apps else []
    reply = "\n".join(f"{app} [{key}] {body}" for app, key, body in rows[:8])
    reply = reply or "No matching records in your enabled Mac sources."
    if len(rows) > 8:
        reply += "\nShowing the eight best matches. Refine the search to narrow the results."
    return {"private": True, "reply": reply}


def sync(state, library, query=None, app_filter=None, *, files_home=None, knowledge=(),
         lock_timeout=30, refresh_existing_files=False):
    try:
        match = search_terms(query) if query is not None else ""
    except ValueError as error:
        return {"private": True, "reply": str(error)}
    state.mkdir(mode=0o700, parents=True, exist_ok=True)
    path = state / mac_context.INDEX_NAME
    os.close(os.open(path, os.O_CREAT | os.O_RDWR, 0o600))
    with closing(sqlite3.connect(path, timeout=lock_timeout)) as db, db:
        db.execute("PRAGMA journal_mode=WAL")
        db.execute("PRAGMA secure_delete=ON")
        db.execute("BEGIN IMMEDIATE")
        db.execute("""CREATE VIRTUAL TABLE IF NOT EXISTS personal USING fts5(
            app UNINDEXED, source UNINDEXED, record UNINDEXED, body, tokenize='unicode61')""")
        memory_connections.ensure_project_catalog(db)
        enabled = mac_context.enabled(state)
        db.execute("""CREATE TABLE IF NOT EXISTS indexed_sources(
            source TEXT PRIMARY KEY, signature TEXT NOT NULL)""")
        db.execute("CREATE TEMP TABLE stage(record TEXT PRIMARY KEY, body TEXT)")
        db.execute("CREATE TEMP TABLE old(record TEXT PRIMARY KEY, id INTEGER)")
        db.execute("""CREATE TABLE IF NOT EXISTS source_summary(source TEXT PRIMARY KEY, app TEXT,
                      signature TEXT, count INTEGER, relatives TEXT)""")
        active = set()
        unavailable = set()
        for app, paths in mac_context.sources(library).items():
            if app not in enabled:
                continue
            if not paths:
                unavailable.add(app)
            for source in paths:
                src = str(source)
                try:
                    refresh_source(db, app, source)
                except (OSError, SourceUnavailable):
                    unavailable.add(app)
                    continue
                active.add(src)
        source = personal_files.SOURCE
        if refresh_existing_files and db.execute(
            "SELECT 1 FROM source_summary WHERE source=?", (source,)
        ).fetchone():
            files_home = library.parent
        if files_home is not None:
            count = refresh_files(db, files_home)
            store_import_count(db, source, "Files", count)
        if db.execute("SELECT 1 FROM source_summary WHERE source=?", (source,)).fetchone():
            active.add(source)
            enabled.add("Files")
        for kind, records in knowledge:
            source = knowledge_sources.PREFIX + kind
            if kind == "Confirmations":
                records = (
                    (f"{app}:{origin}:{key}", body)
                    for app, origin, key, body in db.execute(
                        """SELECT app,source,record,body FROM personal WHERE personal MATCH ?
                           AND app IN ('Mail','Mail archive','Messages','WhatsApp')""",
                        ('"booking reference" OR "reservation confirmed" OR "order confirmation" OR '
                         '"tracking number" OR "ticket confirmation" OR "itinerary confirmation"',),
                    ) if (app == "Mail archive" or origin in active) and knowledge_sources.CONFIRMATION.search(body)
                )
            count = refresh_import(db, kind, source, records)
            store_import_count(db, source, kind, count)
        for source, kind in db.execute("SELECT source,app FROM source_summary WHERE source GLOB ?",
                                       (knowledge_sources.PREFIX + "*",)):
            active.add(source)
            enabled.add(kind)
        for kind in ("Mail", "Messages", "WhatsApp"):
            if kind not in enabled:
                db.execute("DELETE FROM personal WHERE source=? AND record GLOB ?",
                           (knowledge_sources.PREFIX + "Confirmations", kind + ":*"))
        stored = {r[0] for r in db.execute("SELECT source FROM source_summary UNION SELECT source FROM indexed_sources")}
        for stale in stored - active:
            db.execute("DELETE FROM indexed_projects WHERE source=?", (stale,))
            db.execute("DELETE FROM personal WHERE source=?", (stale,))
            db.execute("DELETE FROM indexed_sources WHERE source=?", (stale,))
            db.execute("DELETE FROM source_summary WHERE source=?", (stale,))
        counts = dict(db.execute("SELECT app,sum(count) FROM source_summary GROUP BY app HAVING sum(count)>0"))
        relatives = [name for row in db.execute("SELECT relatives FROM source_summary WHERE app='Contacts'")
                     for name in json.loads(row[0])]
        publish_overview(state, relatives, counts)
        if query is None:
            return counts
        if app_filter and app_filter not in enabled:
            return {"private": True, "reply": f"{app_filter} is disabled in private sources."}
        rows = db.execute("""SELECT app,record,snippet(personal,3,'','',' … ',24)
                             FROM personal WHERE personal MATCH ? AND (? IS NULL OR app=?)
                             ORDER BY rank,rowid LIMIT 9""", (match, app_filter, app_filter)).fetchall()
        reply = "\n".join(f"{app} [{key}] {body}" for app, key, body in rows[:8])
        reply = reply or "No matching records in your enabled Mac sources."
        if len(rows) > 8:
            reply += "\nShowing the eight best matches. Refine the search to narrow the results."
        if unavailable:
            reply += " Unavailable: " + ", ".join(sorted(unavailable)) + "."
        return {"private": True, "reply": reply}


def sources_changed(db, library, apps):
    current = {}
    for app, sources in mac_context.sources(library).items():
        if app in apps:
            for source in sources:
                try:
                    current[str(source)] = source_signature(app, source)
                except OSError:
                    continue
    cached = {
        source: stamp
        for source, stamp, app in db.execute(
            """SELECT i.source,i.signature,s.app FROM indexed_sources i
               JOIN source_summary s USING(source)"""
        )
        if app in apps
    }
    return current != cached


def refresh_files(db, home):
    source = personal_files.SOURCE
    db.execute("CREATE TABLE IF NOT EXISTS file_signatures(record TEXT PRIMARY KEY, stamp TEXT NOT NULL)")
    stamps = dict(db.execute("SELECT record,stamp FROM file_signatures"))
    existing = dict(db.execute("SELECT record,rowid FROM personal WHERE source=?", (source,)))
    reader = shutil.which("pdftotext")
    seen = set()
    for relative, path, info in personal_files.candidates(home):
        seen.add(relative)
        stamp = repr((1, info.st_ino, info.st_dev, info.st_size, info.st_mtime_ns,
                      info.st_ctime_ns, getattr(info, "st_flags", 0), reader))
        row = existing.get(relative)
        if row is not None and stamps.get(relative) == stamp:
            continue
        try:
            body = personal_files.indexed_body(relative, path, info, reader)
        except OSError:
            seen.remove(relative)
            continue
        if row is None:
            db.execute("INSERT INTO personal VALUES('Files',?,?,?)", (source, relative, body))
        else:
            db.execute("UPDATE personal SET body=? WHERE rowid=? AND body IS NOT ?", (body, row, body))
        db.execute("INSERT OR REPLACE INTO file_signatures VALUES(?,?)", (relative, stamp))
    db.executemany("DELETE FROM personal WHERE rowid=?", ((row,) for key, row in existing.items() if key not in seen))
    db.executemany("DELETE FROM file_signatures WHERE record=?", ((key,) for key in stamps.keys() - seen))
    return len(seen)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compact", action="store_true", help="Merge search segments and reclaim unused SQLite pages.")
    parser.add_argument("--files", action="store_true", help="Refresh the local home-folder document index.")
    parser.add_argument("--knowledge", nargs="*", choices=knowledge_sources.APPS,
                        help="Refresh selected knowledge sources, or all when no source is specified.")
    parser.add_argument("--apple-notes", action="store_true",
                        help="Read Apple Notes via macOS Automation permission.")
    parser.add_argument("--notes-vault", type=Path,
                        help="Read supported files from an Obsidian vault.")
    args = parser.parse_args()
    state = Path(__file__).resolve().parent / "state"
    home = Path.home()
    kinds = () if args.knowledge is None else args.knowledge or knowledge_sources.APPS
    imports = {kind: dict(knowledge_sources.collect(state, home, kind)) for kind in kinds}
    if args.apple_notes or args.notes_vault:
        folder = state / "knowledge-imports" / "Notes"
        folder.mkdir(mode=0o700, parents=True, exist_ok=True)
        capture = folder / "notes-capture.jsonl"
        notes = {}
        if capture.is_file():
            with capture.open(encoding="utf-8") as stream:
                for line in stream:
                    row = json.loads(line)
                    notes[row["id"]] = row["text"]
        if args.apple_notes:
            notes = {key: body for key, body in notes.items() if not key.startswith("apple-notes:")}
            try:
                notes.update(knowledge_sources.apple_notes())
            except (OSError, subprocess.SubprocessError, ValueError):
                parser.error("Unable to read Apple Notes. Check macOS Automation permission for the launching app.")
        if args.notes_vault:
            vault = args.notes_vault.resolve()
            if not vault.is_dir():
                parser.error("--notes-vault must name an existing folder")
            prefix = f"obsidian:{vault}:"
            notes = {key: body for key, body in notes.items() if not key.startswith(prefix)}
            notes.update((prefix + key, body) for key, body in personal_files.records(vault.parent, (vault.name,)))
        with tempfile.NamedTemporaryFile(mode="w", dir=folder, delete=False) as stream:
            for key, body in notes.items():
                stream.write(json.dumps({"id": key, "text": body}, ensure_ascii=False) + "\n")
        Path(stream.name).replace(capture)
        imports["Notes"] = dict(knowledge_sources.collect(state, home, "Notes"))
    print(sync(state, home / "Library", files_home=home if args.files else None,
               knowledge=((kind, rows.items()) for kind, rows in imports.items())))
    if args.compact:
        path = state / mac_context.INDEX_NAME
        before = path.stat().st_size
        with closing(sqlite3.connect(path, timeout=30, isolation_level=None)) as db:
            db.execute("INSERT INTO personal(personal) VALUES('optimize')")
            db.execute("INSERT INTO personal(personal) VALUES('integrity-check')")
            db.execute("VACUUM")
        print(f"Index compacted from {before:,} to {path.stat().st_size:,} bytes.")
